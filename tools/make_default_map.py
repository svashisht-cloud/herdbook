#!/usr/bin/env python3
"""Generate the dashboard's default yard map (ROS map_server format: PGM + YAML).

Stdlib only. Writes dashboard/public/maps/yard.pgm (binary P5) and yard.yaml.
Run from anywhere: python3 tools/make_default_map.py

Layout (map frame, metres, y up): free floor, a 0.5 m outer wall, two rack rows
and two pillars inside the robots' loop, and one asymmetric marker block in the
top-right corner only, so a flipped or mirrored map is easy to spot. The robots'
loop is read from robot/herdbook_robot/fake_robot.py, and tools/test_default_map.py
checks the whole loop plus a safety margin stays free.
"""
import ast
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FAKE_ROBOT = ROOT / "robot" / "herdbook_robot" / "fake_robot.py"
OUT_DIR = ROOT / "dashboard" / "public" / "maps"

WIDTH_M, HEIGHT_M = 100.0, 60.0
RESOLUTION = 0.1  # metres per pixel
FREE, OCCUPIED = 254, 0
WALL_M = 0.5
SAFETY_MARGIN_M = 3.0  # robot half-length (~1 m) plus 2 m

# Obstacles as (x0, y0, x1, y1) in map metres. Marker: a 4 x 4 m block with a 1.5 x 1.5 m notch cut out of
# its bottom-left corner, so even its own shape isn't symmetric.
RACKS = [(28.0, 23.0, 72.0, 25.0), (28.0, 35.0, 72.0, 37.0)]
PILLARS = [(39.5, 29.5, 40.5, 30.5), (59.5, 29.5, 60.5, 30.5)]
MARKER = (91.0, 51.0, 95.0, 55.0)
MARKER_NOTCH = (91.0, 51.0, 92.5, 52.5)


def robot_loop():
    """CENTER_X, CENTER_Y, RADIUS_X, RADIUS_Y from fake_robot.py, read without importing it (it needs rclpy)."""
    values = {}
    for node in ast.parse(FAKE_ROBOT.read_text()).body:
        if isinstance(node, ast.Assign):
            names = [t.id for t in node.targets if isinstance(t, ast.Name)]
            tuples = [t for t in node.targets if isinstance(t, ast.Tuple)]
            if names:
                try:
                    values[names[0]] = ast.literal_eval(node.value)
                except ValueError:
                    pass
            for t in tuples:
                vals = ast.literal_eval(node.value)
                for elt, v in zip(t.elts, vals):
                    values[elt.id] = v
    return values["CENTER_X"], values["CENTER_Y"], values["RADIUS_X"], values["RADIUS_Y"]


def build():
    """Pixels, top row first (PGM order)."""
    w = round(WIDTH_M / RESOLUTION)
    h = round(HEIGHT_M / RESOLUTION)
    grid = [[FREE] * w for _ in range(h)]  # grid[row_from_bottom][col]

    def fill(x0, y0, x1, y1, value=OCCUPIED):
        for j in range(max(0, round(y0 / RESOLUTION)), min(h, round(y1 / RESOLUTION))):
            for i in range(max(0, round(x0 / RESOLUTION)), min(w, round(x1 / RESOLUTION))):
                grid[j][i] = value

    wall = WALL_M
    fill(0, 0, WIDTH_M, wall)
    fill(0, HEIGHT_M - wall, WIDTH_M, HEIGHT_M)
    fill(0, 0, wall, HEIGHT_M)
    fill(WIDTH_M - wall, 0, WIDTH_M, HEIGHT_M)
    for box in RACKS + PILLARS:
        fill(*box)
    fill(*MARKER)
    fill(*MARKER_NOTCH, value=FREE)
    return w, h, [bytes(row) for row in reversed(grid)]  # PGM row 0 is the top of the image


def pgm_bytes():
    w, h, rows = build()
    header = f"P5\n# Herdbook default yard, generated by tools/make_default_map.py\n{w} {h}\n255\n".encode()
    return header + b"".join(rows)


YAML = f"""image: yard.pgm
resolution: {RESOLUTION}
origin: [0, 0, 0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
"""


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "yard.pgm").write_bytes(pgm_bytes())
    (OUT_DIR / "yard.yaml").write_text(YAML)
    cx, cy, rx, ry = robot_loop()
    print(f"wrote {OUT_DIR / 'yard.pgm'} and yard.yaml; robot loop ({cx}, {cy}) +/- ({rx}, {ry})")


if __name__ == "__main__":
    main()
