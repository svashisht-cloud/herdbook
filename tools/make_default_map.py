#!/usr/bin/env python3
"""Generate the dashboard's default floor map (ROS map_server format: PGM + YAML).

Stdlib only. Writes dashboard/public/maps/yard.pgm (binary P5) and yard.yaml.
Run from anywhere: python3 tools/make_default_map.py

The layout is rasterized from robot/config/floor.json, the same file fake_robot routes
and its lidar use: every wall and rack is occupied, the rest is free. One extra block,
an asymmetric marker in the top-right corner, makes a flipped or mirrored map easy to
spot. tools/test_default_map.py checks every robot's route plus a margin stays free.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FLOOR = ROOT / "robot" / "config" / "floor.json"
OUT_DIR = ROOT / "dashboard" / "public" / "maps"

RESOLUTION = 0.1  # metres per pixel
FREE, OCCUPIED = 254, 0
SAFETY_MARGIN_M = 1.5  # route centreline to any obstacle: robot half-width (~1.1 m) plus 0.4 m

# Marker: a 4 x 4 m block with a 1.5 x 1.5 m notch cut out of its bottom-left corner, so even its
# own shape isn't symmetric. It's map-only (not in floor.json), in the open floor east of the racks.
MARKER = (91.0, 51.0, 95.0, 55.0)
MARKER_NOTCH = (91.0, 51.0, 92.5, 52.5)


def load_floor():
    return json.loads(FLOOR.read_text())


def build():
    """Pixels, top row first (PGM order)."""
    floor = load_floor()
    w = round(floor["width"] / RESOLUTION)
    h = round(floor["height"] / RESOLUTION)
    grid = [[FREE] * w for _ in range(h)]  # grid[row_from_bottom][col]

    def fill(x0, y0, x1, y1, value=OCCUPIED):
        for j in range(max(0, round(y0 / RESOLUTION)), min(h, round(y1 / RESOLUTION))):
            for i in range(max(0, round(x0 / RESOLUTION)), min(w, round(x1 / RESOLUTION))):
                grid[j][i] = value

    for box in floor["walls"] + floor["racks"]:
        fill(*box)
    fill(*MARKER)
    fill(*MARKER_NOTCH, value=FREE)
    return w, h, [bytes(row) for row in reversed(grid)]  # PGM row 0 is the top of the image


def pgm_bytes():
    w, h, rows = build()
    header = f"P5\n# Herdbook default floor, generated by tools/make_default_map.py from robot/config/floor.json\n{w} {h}\n255\n".encode()
    return header + b"".join(rows)


YAML = f"""image: yard.pgm
resolution: {RESOLUTION}
origin: [0, 0, 0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
"""


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "yard.pgm").write_bytes(pgm_bytes())
    (OUT_DIR / "yard.yaml").write_text(YAML)
    print(f"wrote {OUT_DIR / 'yard.pgm'} and yard.yaml from {FLOOR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
